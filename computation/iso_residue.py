#!/usr/bin/env python3
"""
Explicit isomorphism search between the residue-F_q rings that share all
invariants.  R is generated by zeta and the pc generators g_i of J, so an
isomorphism is fixed by zeta' (a unit of order q-1 in R') and images h_i in J(R')
satisfying the relations of J (searched by backtracking); survivors must also
satisfy zeta' h_i = image of L(g_i), h_i zeta' = image of R(g_i), and are then
checked on all pairs of elements.
"""
import json
import sys
from collections import defaultdict
from itertools import combinations

sys.path.insert(0, ".")
from enum_local_F2 import Ring, bits
from enum_residue_Fq import build_R


def load(path, q):
    out = []
    for d in json.load(open(path)):
        J = Ring(d["J"]["m"], d["J"]["P"], d["J"]["Q"], d["J"]["c"])
        N, add, mul, one, nJ = build_R(J, q, tuple(d["L"]), tuple(d["R"]))
        out.append(dict(J=J, L=d["L"], R=d["R"], N=N, add=add, mul=mul, one=one,
                        inv=tuple(d["inv"]), q=q))
    return out


def code(q, nJ, a, x):
    return a * nJ + x  # elements were listed as (a, x) with a outer, x inner


def isomorphic(X, Y):
    q, J = X["q"], X["J"]
    nJ = 1 << J.m
    N, add2, mul2, one2 = Y["N"], Y["add"], Y["mul"], Y["one"]
    if X["N"] != N:
        return False
    r = {4: 2, 8: 3}[q]
    # units of order q-1 in Y
    def power(x, k):
        y = one2
        for _ in range(k):
            y = mul2[y][x]
        return y
    zetas = [z for z in range(N) if power(z, q - 1) == one2 and
             all(power(z, d) != one2 for d in range(1, q - 1))]
    Jy = [x for x in range(N) if not any(mul2[x][y] == one2 for y in range(N))]
    Jyset = set(Jy)

    def sumY(vals):
        s = 0
        for v in vals:
            s = add2[s][v]
        return s

    m = J.m
    for zp in zetas:
        zpow = [one2]
        for _ in range(r):
            zpow.append(mul2[zpow[-1]][zp])
        imgs = [0] * m

        def Jimg(x):
            return sumY(imgs[i] for i in bits(x))

        def full_map():
            return [add2[sumY(zpow[j] for j in bits(a))][Jimg(x)]
                    for a in range(q) for x in range(nJ)]

        def rec(i, S):
            if i < 0:
                if Jimg(J.c) != add2[one2][one2]:
                    return False
                for k in range(m):
                    if mul2[zp][imgs[k]] != Jimg(X["L"][1 << k]):
                        return False
                    if mul2[imgs[k]][zp] != Jimg(X["R"][1 << k]):
                        return False
                F = full_map()
                if len(set(F)) != N:
                    return False
                A1, M1 = X["add"], X["mul"]
                return all(F[A1[u][v]] == add2[F[u]][F[v]] and F[M1[u][v]] == mul2[F[u]][F[v]]
                           for u in range(N) for v in range(N))
            for h in Jy:
                if h in S:
                    continue
                if add2[h][h] != Jimg(J.P[i]):
                    continue
                imgs[i] = h
                ok = all(mul2[h][imgs[j]] == Jimg(J.Q[i][j]) and
                         mul2[imgs[j]][h] == Jimg(J.Q[j][i]) for j in range(i, m))
                if ok:
                    T = set(S) | {add2[h][s] for s in S}
                    if rec(i - 1, T):
                        return True
            imgs[i] = 0
            return False

        if rec(m - 1, {0}):
            return True
    return False


for path, q in [("residue_F8_order64.json", 8), ("residue_F4_order64.json", 4)]:
    rings = load(path, q)
    groups = defaultdict(list)
    for i, R in enumerate(rings):
        groups[R["inv"]].append(i)
    pairs = [p for g in groups.values() for p in combinations(g, 2)]
    selfok = all(isomorphic(R, R) for R in rings)
    res = [(a, b, isomorphic(rings[a], rings[b])) for a, b in pairs]
    print(f"residue F{q}: {len(rings)} rings, self-isomorphism found for all: {selfok}; "
          f"same-invariant pairs {[(a, b) for a, b, _ in res]} isomorphic: {[iso for *_, iso in res]}")
